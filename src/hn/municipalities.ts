export interface Territory {
  department: { code: string; name: string }
  municipality: { code: string; name: string }
}

// Checks the leading DDMM digits shared by DNI and RTN.
export function checkTerritory(digits: string): ValidationError | undefined {
  const department = departments[Number(digits.slice(0, 2)) - 1]
  if (!department) return 'INVALID_DEPARTMENT'
  const index = Number(digits.slice(2, 4)) - 1
  if (index < 0 || index >= department.municipalities.length)
    return 'INVALID_MUNICIPALITY'
}

export function territory(digits: string): Territory {
  const department = departments[Number(digits.slice(0, 2)) - 1]!
  return {
    department: { code: digits.slice(0, 2), name: department.name },
    municipality: {
      code: digits.slice(0, 4),
      name: department.municipalities[Number(digits.slice(2, 4)) - 1]!,
    },
  }
}

export function checkYear(year: number): ValidationError | undefined {
  // Registration year, which can be later than the birth year.
  if (year < 1900 || year > new Date().getFullYear()) return 'INVALID_YEAR'
}
